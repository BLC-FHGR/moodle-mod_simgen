namespace mod_simgen\event;

/**
 * A new version of a simulation was generated by the AI.
 *
 * @package    mod_simgen
 * @copyright  2026 FH Graubünden
 * @license    https://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class simulation_generated extends \core\event\base {

    /**
     * Init method.
     */
    protected function init() {
        $this->data['crud'] = 'c';
        $this->data['edulevel'] = self::LEVEL_TEACHING;
        $this->data['objecttable'] = 'simgen_versions';
    }

    /**
     * Event name.
     *
     * @return string
     */
    public static function get_name() {
        return get_string('event_simulation_generated', 'mod_simgen');
    }

    /**
     * Description.
     *
     * @return string
     */
    public function get_description() {
        return "The user with id '{$this->userid}' generated version '{$this->other['versionnum']}' of the simulation "
            . "with course module id '{$this->contextinstanceid}'.";
    }

    /**
     * Related URL.
     *
     * @return \moodle_url
     */
    public function get_url() {
        return new \moodle_url('/mod/simgen/view.php', ['id' => $this->contextinstanceid, 'version' => $this->objectid]);
    }

    /**
     * Mapping for restore.
     *
     * @return array
     */
    public static function get_objectid_mapping() {
        return ['db' => 'simgen_versions', 'restore' => 'simgen_version'];
    }

    /**
     * Mapping of 'other' for restore.
     *
     * @return bool
     */
    public static function get_other_mapping() {
        return false;
    }
}
